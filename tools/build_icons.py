#!/usr/bin/env python3
"""Build the icon set from assets/icons/icons.json (single source, 15 DEMO-08 / 13 BODY-02).

Writes runtime/kz-icons.js (KZIcons for the HTML tracks) and assets/icons/kangzhe/<name>.svg, the file form
ppt-master's icon pool expects (copy the folder to <project>/icons/kangzhe/ and reference
<use data-icon="kangzhe/<name>" …/>). Run after editing icons.json.
"""
from pathlib import Path
import json
R = Path(__file__).resolve().parents[1]
SRC = json.loads((R / 'assets/icons/icons.json').read_text(encoding='utf-8'))['icons']
STROKE = 1.8

def svg_file(d):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            f'stroke="currentColor" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"><path d="{d}"/></svg>\n')

def js(icons):
    rows = ',\n'.join(f"    {json.dumps(n)}: {json.dumps(v['d'])}" for n, v in icons.items())
    return f'''/* Kangzhe 7.2 — line icons for stages and template pages (15 DEMO-08, 13 BODY-02). Generated by tools/build_icons.py
   from assets/icons/icons.json; do not edit by hand. 24×24 grid, stroke {STROKE}, round joins; colour follows currentColor.
     KZIcons.svg(name, {{title}}) → <svg>      KZIcons.names → [...]
   Icons name things the material names (documents, subjects, sites, labs, visits, systems); they do not stand in for
   mechanisms, anatomy or study results (04: no invented mechanism pictures). Third-party sources: assets/icons/NOTICE.md. */
(function (global) {{
  'use strict';
  const P = {{
{rows}
  }};
  const NS = 'http://www.w3.org/2000/svg';
  function svg(name, {{ title }} = {{}}) {{
    if (!P[name]) throw Error('未知图标：' + name);
    const s = document.createElementNS(NS, 'svg');
    s.setAttribute('viewBox', '0 0 24 24'); s.setAttribute('fill', 'none'); s.setAttribute('stroke', 'currentColor');
    s.setAttribute('stroke-width', '{STROKE}'); s.setAttribute('stroke-linecap', 'round'); s.setAttribute('stroke-linejoin', 'round');
    s.setAttribute('class', 'kz-icon'); s.dataset.icon = name;
    if (title) {{ const t = document.createElementNS(NS, 'title'); t.textContent = title; s.append(t); }} else s.setAttribute('aria-hidden', 'true');
    const p = document.createElementNS(NS, 'path'); p.setAttribute('d', P[name]); s.append(p);
    return s;
  }}
  global.KZIcons = {{ svg, names: Object.keys(P) }};
}})(window);
'''

def main():
    out = R / 'assets/icons/kangzhe'; out.mkdir(parents=True, exist_ok=True)
    for f in out.glob('*.svg'):
        if f.stem not in SRC: f.unlink()
    for n, v in SRC.items():
        (out / f'{n}.svg').write_text(svg_file(v['d']), encoding='utf-8')
    (R / 'runtime/kz-icons.js').write_text(js(SRC), encoding='utf-8')
    print(f'{len(SRC)} icons → runtime/kz-icons.js, assets/icons/kangzhe/')

if __name__ == '__main__':
    main()
